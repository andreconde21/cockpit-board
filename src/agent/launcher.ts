import { App, TFile } from "obsidian";
import type { AgentProfile, CardDelivery, CardFrontmatter, CockpitBoardSettings, SessionMode } from "../types";
import { loginEnv, nodeApis, runProcess, startDetached, which, type NodeApis, type RunResult } from "../node";
import { cardIdOf } from "./card-id";
import { absolutePath, boardLink, buildContext, cardTitle } from "./context";
import type { ResolvedMachine } from "./machines";
import { psCall, psq, renderTemplate, shDir, shJoin, shq, slug, splitArgs } from "./shell";

// The agent launcher. Rules every path below follows:
// - Card text (the prompt) is only ever written to a file, sent on stdin, or
//   passed as one argv element to a program started without a shell. It is
//   never part of a script, a shell string or a terminal command line.
// - Scripts and shell strings are built from settings values and our own
//   slugs only, each quoted with shq/psq.

/** Remote folder for uploaded cards and prompts (POSIX, `~` expands). */
const REMOTE_CACHE = "~/.cache/cockpit-board";
/** Windows caps a command line near 32 K characters; stay well below. */
const MAX_ARGV_PROMPT = 24000;

export interface LaunchPlan {
  file: TFile;
  agent: AgentProfile;
  /** null = this computer. */
  machine: ResolvedMachine | null;
  session: SessionMode;
  delivery: CardDelivery;
  /** Working directory; "" = default (vault root locally, home remotely). */
  cwd: string;
  /** The final prompt, as shown (and possibly edited) in the dialog. */
  prompt: string;
}

export class LaunchError extends Error {
  constructor(message: string, public runDir?: string) { super(message); }
}

// ── Pure helpers (unit tested) ──

/** Where the agent reads the card on a remote machine, or undefined when inline. */
export function remoteCardFile(delivery: CardDelivery, machine: ResolvedMachine | null, cardId: string): string | undefined {
  if (!machine || delivery === "inline") return undefined;
  if (delivery === "shared") return joinPosix(machine.sharedRemote, "cockpit", `${slug(cardId)}.md`);
  return `${REMOTE_CACHE}/cards/${slug(cardId)}.md`;
}

function joinPosix(...parts: string[]): string {
  return parts.map((p, i) => (i === 0 ? p.replace(/\/+$/, "") : p.replace(/^\/+|\/+$/g, ""))).filter(Boolean).join("/");
}

/**
 * herdr parses a positional argument that starts with "-" as an option (it
 * ignores "--"), so such a prompt would fail. A leading space is harmless.
 */
export function herdrText(text: string): string {
  return text.startsWith("-") ? ` ${text}` : text;
}

/** SSH options start with "-"; a target must not. */
export function checkSshTarget(target: string): string {
  if (!target || target.startsWith("-")) throw new Error(`Invalid SSH target "${target}".`);
  return target;
}

/** The pointer prompt used when the prompt itself cannot travel as text. */
export function pointerPrompt(path: string): string {
  return `Your task is in the file ${path}. Read it and follow it.`;
}

/** argv for the agent: command plus the profile's arguments. */
export function agentArgv(agent: AgentProfile): string[] {
  return [agent.command.trim() || "claude", ...splitArgs(agent.args)];
}

/** A POSIX `cd <dir> && <agent> "$(cat <prompt file>)"` line. */
export function posixAgentLine(argv: string[], promptFile: string, cwd: string): string {
  const promptExpr = promptFile.startsWith("~/") ? `$(cat ${shDir(promptFile)})` : `$(cat ${shq(promptFile)})`;
  const cd = cwd ? `cd ${shDir(cwd)} && ` : "";
  return `${cd}${shJoin(argv)} "${promptExpr}"`;
}

/** Local POSIX launch script: login PATH, cd, run the agent, keep a shell. */
export function posixScript(opts: { pathEnv?: string; body: string }): string {
  return [
    "#!/bin/sh",
    "# Generated by Cockpit Board. Card text is read from files, never inlined here.",
    ...(opts.pathEnv ? [`export PATH=${shq(opts.pathEnv)}`] : []),
    opts.body,
    "exec \"${SHELL:-/bin/sh}\" -l",
    "",
  ].join("\n");
}

/** Local PowerShell launch script. */
export function powershellScript(lines: string[]): string {
  return ["# Generated by Cockpit Board. Card text is read from files, never inlined here.", ...lines, ""].join("\r\n");
}

/** Template variables for a card; `cardFile` is where the agent reads it. */
export async function promptVars(app: App, file: TFile, cardFile?: string): Promise<Record<string, string>> {
  const fm = app.metadataCache.getFileCache(file)?.frontmatter ?? {};
  const labels: unknown = fm.labels;
  const abs = absolutePath(app, file) ?? file.path;
  return {
    context: await buildContext(app, file, cardFile ? { cardFile, includeBody: false } : {}),
    id: cardIdOf(app, file),
    title: cardTitle(app, file),
    path: file.path,
    absPath: abs,
    cardFile: cardFile ?? abs,
    boardLink: boardLink(app, file),
    uri: boardLink(app, file),
    project: typeof fm.project === "string" ? fm.project : "",
    labels: Array.isArray(labels) ? labels.filter((l) => typeof l === "string").join(", ") : "",
  };
}

/** The rendered prompt for a card and agent. */
export async function renderPrompt(app: App, settings: CockpitBoardSettings, file: TFile, agent: AgentProfile, cardFile?: string): Promise<string> {
  const template = agent.promptTemplate.trim() || settings.agentPromptTemplate;
  return renderTemplate(template, await promptVars(app, file, cardFile));
}

/** Terminal command argv with `{script}` replaced; the template is a settings value. */
export function terminalArgv(template: string, script: string): string[] {
  const argv = splitArgs(template);
  if (!argv.some((a) => a.includes("{script}"))) argv.push("{script}");
  return argv.map((a) => a.split("{script}").join(script));
}

